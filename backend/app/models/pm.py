from sqlalchemy import Column, Integer, String
from ..database import Base
class PM(Base):
    __tablename__="pms"   #DATABASE MAI ISI NAAM KA TABLE HOGA
    id=Column(Integer,primary_key=True,index=True) #DATABASE AUTOGENERATED ID FOR RECORDS
    name=Column(String,nullable=False)
    email=Column(String,unique=True,nullable=False) #SZABIST PROVIDES UNIQUE EMAIL
    password_hash=Column(String, nullable=False)
    program=Column(String, nullable=False) #SPECIFIC PROGRAM
    year=Column(Integer, nullable=False) #YEAR WISE LIKE FIRST YEAR,2ND,3RD OR 4TH
